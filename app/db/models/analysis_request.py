import uuid
from datetime import datetime
from decimal import Decimal
from typing import Any

from sqlalchemy import ForeignKey, Index, Text
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class AnalysisRequest(Base):
    """Fase 5 — POST /analyze. Representa um pedido do frontend de ponta a
    ponta (produto + países), diferente de `Job`/`JobTask` (que modelam uma
    *task* de coleta individual, granularidade menor). Processado via
    `BackgroundTasks` do FastAPI (v1 — sem worker/fila dedicada ainda, ver
    memory marketmind_mos_engine): se a API reiniciar no meio do
    processamento, o registro fica travado em `running` sem retomar —
    limitação aceita explicitamente pelo usuário.

    `estimated_price`/`price_currency` vêm de `POST /catalog/identify-image`
    (uma estimativa da LLM a partir da foto, não de API real) — guardados só
    como contexto, nunca entram em nenhum cálculo de indicador ou MOS.
    """

    __tablename__ = "analysis_requests"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    status: Mapped[str] = mapped_column(nullable=False)
    entity_key: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("product_catalog.entity_key"), nullable=True
    )
    canonical_title: Mapped[str | None] = mapped_column(nullable=True)
    # Por qual dos quatro passos o catálogo chegou nesta entidade: `alias`,
    # `trigram`, `llm` ou `created`. Só `created` significa produto inédito —
    # ver a migration 039. O score acompanha só o `trigram`, que é o único que
    # decide por número.
    catalog_method: Mapped[str | None] = mapped_column(nullable=True)
    catalog_match_score: Mapped[Decimal | None] = mapped_column(nullable=True)
    # Só no passo `llm` — ver a migration 040.
    catalog_match_reasoning: Mapped[str | None] = mapped_column(Text, nullable=True)
    # O texto que o comprador digitou. O outro lado do par: sem ele, "picanha,
    # coincidência exata" é ilegível para quem pediu "top sirloin cap".
    catalog_query_text: Mapped[str | None] = mapped_column(Text, nullable=True)
    countries: Mapped[list[str]] = mapped_column(JSONB, nullable=False)
    estimated_price: Mapped[Decimal | None] = mapped_column(nullable=True)
    price_currency: Mapped[str | None] = mapped_column(nullable=True)
    # The buyer's own free-text description/question from the frontend. Used as
    # the identify-image hint AND passed to the final explanation LLM so it can
    # answer what the user asked — strictly from the deterministic packet, never
    # inventing data (Cap. 4 §4.0). Nullable: analyses may be submitted without one.
    user_prompt: Mapped[str | None] = mapped_column(Text, nullable=True)
    result: Mapped[list[dict[str, Any]] | None] = mapped_column(JSONB, nullable=True)
    # The full per-country evidence packet the explanation service assembles
    # (glossary + weights + demand ruler + each country's MOS, the 7 dimension
    # subscores and every deterministic signal with its explanation sentence).
    # Persisted so the frontend renders the rich MOS breakdown from one GET. The
    # dimension subscores live ONLY here — they are computed transiently for the
    # MOS and not otherwise stored. Nullable: rebuilt lazily on read when absent.
    breakdown: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)
    # Business-facing narrative of the MOS ranking, generated by the final LLM
    # inference service (marketmind-ollma-llm / qwen3:14b) from the deterministic
    # result. Best-effort — null if the LLM service was unavailable. The LLM only
    # explains; it never computes or alters any score (Cap. 4 §4.0).
    explanation: Mapped[str | None] = mapped_column(Text, nullable=True)
    error_message: Mapped[str | None] = mapped_column(Text, nullable=True)
    # No que a análise está esperando AGORA (migration 033). Uma análise que
    # insiste numa fonte fora do ar é legítima e pode levar horas; sem esta
    # frase ela é indistinguível de uma travada.
    progress: Mapped[str | None] = mapped_column(Text, nullable=True)
    # Até quando vale insistir (decisão D5). Persistido, não só em memória,
    # porque quem retoma depois de um restart precisa saber se ainda está
    # dentro do orçamento ou se o pedido já deveria ter falhado.
    # Quem está executando esta análise AGORA, e desde quando. O `status` sozinho
    # não responde isso: uma análise fica `running` por horas legitimamente, e
    # `running` não distingue "um processo está trabalhando nisso" de "o processo
    # que trabalhava nisso morreu".
    #
    # Sem isso, a retomada só podia ser por silêncio — esperar 15 minutos sem
    # batimento antes de agir. Com a reivindicação, um agente que acabou de subir
    # retoma na hora o que ninguém segura, e dois agentes podem rodar lado a lado
    # sem um roubar a análise do outro.
    claimed_by: Mapped[str | None] = mapped_column(nullable=True)
    claimed_at: Mapped[datetime | None] = mapped_column(nullable=True)
    deadline_at: Mapped[datetime | None] = mapped_column(nullable=True)
    # Último sinal de vida (migration 034). Com D3 uma análise legítima fica
    # horas em `running`, então o status sozinho não distingue quem está
    # trabalhando de quem morreu com o pod. Atualizado a cada país coberto e a
    # cada tentativa do laço de insistência.
    heartbeat_at: Mapped[datetime | None] = mapped_column(nullable=True)
    created_at: Mapped[datetime] = mapped_column(nullable=False, default=datetime.utcnow)
    finished_at: Mapped[datetime | None] = mapped_column(nullable=True)

    __table_args__ = (Index("ix_analysis_requests_status", "status"),)
